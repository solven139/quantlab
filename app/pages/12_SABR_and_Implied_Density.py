import numpy as np
import plotly.graph_objects as go
import streamlit as st
from plotly.subplots import make_subplots

from quantlab import (HestonModel, black_implied_vol, cos_density, fit_sabr, implied_density,
                      otm_prices, sabr_implied_vols, smooth_vols)

BLUE = "#3987e5"
ORANGE = "#d95926"
GREEN = "#1baf7a"
VIOLET = "#4a3aa7"
NEUTRAL = "#8a8985"

st.title("SABR and the Implied Density")
st.markdown(
    "Two tools for reading a smile. **SABR** (Hagan et al. 2002) is a formula for the whole "
    "smile with four parameters. **Breeden-Litzenberger** turns a smile into the probability "
    "distribution the market assigns to the future price, because the second derivative of "
    "call prices in the strike *is* the risk-neutral density (book Ch 4.3.3):"
)
st.latex(r"\frac{dF}{F^{\beta}} = \sigma\,dW_F,\quad \frac{d\sigma}{\sigma} = \nu\,dW_\sigma,"
         r"\quad dW_F\,dW_\sigma=\rho\,dt"
         r"\qquad\qquad f_{S(T)}(K) = \frac{1}{P(0,T)}\,\frac{\partial^2 C}{\partial K^2}")

tab_sabr, tab_bl = st.tabs(["SABR smile", "Implied density"])

# ---------------- Tab 1: SABR ----------------
with tab_sabr:
    st.markdown(
        "SABR isn't a `Model` in this engine: it has no characteristic function, so the COS "
        "pricer can't use it. What it does have is Hagan's closed-form approximation of the "
        "Black implied vol (book eq. 4.61), which makes it the standard way to interpolate "
        "and extrapolate a smile."
    )
    c1, c2, c3, c4, c5 = st.columns(5)
    atm_target = c1.slider("ATM vol level", 0.05, 0.6, 0.2, step=0.01, format="%.2f")
    beta = c2.select_slider("β (fixed)", [0.0, 0.25, 0.5, 0.75, 1.0], value=1.0)
    rho = c3.slider("ρ  skew", -0.95, 0.95, -0.4, step=0.05)
    nu = c4.slider("ν  vol of vol", 0.01, 2.0, 0.6, step=0.01)
    T_s = c5.select_slider("T (years)", [0.1, 0.25, 0.5, 1.0, 2.0], value=0.5)
    Fs = 100.0
    alpha = atm_target * Fs ** (1 - beta)        # alpha in the units that beta implies
    Ks = Fs * np.exp(np.linspace(-0.6, 0.45, 160))
    fig = go.Figure()
    fig.add_scatter(x=Ks, y=sabr_implied_vols(Fs, list(Ks), T_s, alpha, beta, rho, nu),
                    name="your parameters", line=dict(color=BLUE, width=3))
    fig.add_scatter(x=Ks, y=sabr_implied_vols(Fs, list(Ks), T_s, alpha, beta, 0.0, nu),
                    name="ρ = 0", line=dict(color=ORANGE, width=1.5, dash="dash"))
    fig.add_scatter(x=Ks, y=sabr_implied_vols(Fs, list(Ks), T_s, alpha, beta, rho, 1e-6),
                    name="ν = 0", line=dict(color=NEUTRAL, width=1.5, dash="dot"))
    fig.add_vline(x=Fs, line=dict(color=NEUTRAL, width=1), annotation_text="F")
    fig.update_layout(xaxis_title="Strike K (forward F = 100)", yaxis_title="Implied vol",
                      yaxis_tickformat=".0%", height=440)
    st.plotly_chart(fig, width="stretch")
    st.caption(
        "α sets the level, ρ tilts the smile (negative ρ: vol rises when the price falls, the "
        "equity skew), ν bends it into a smile. β also creates skew, so β and ρ partly do the "
        "same job. That's why β is usually fixed (1 for an index, 0.5 for rates) and only "
        "α, ρ, ν are fitted. With ν = 0 and β = 1 the smile is flat: Black-Scholes. "
        "Hagan's formula is an asymptotic expansion: very large ν²T makes it inaccurate, "
        "and far in the low-strike wing it can even imply negative densities."
    )

    st.subheader("SABR fitted to a Heston smile")
    H_demo = HestonModel(r=0.0, kappa=1.5, vbar=0.04, gamma=0.5, rho=-0.7, v0=0.03)
    Kq = Fs * np.exp(np.linspace(-2.0, 1.5, 21) * 0.2 * np.sqrt(T_s))
    ivq = black_implied_vol(otm_prices(H_demo, Fs, Kq, T_s), Fs, Kq, T_s, Kq >= Fs)
    sf = fit_sabr(Fs, Kq, T_s, ivq, beta=beta)
    fine = np.linspace(Kq[0], Kq[-1], 150)
    fig = go.Figure()
    fig.add_scatter(x=Kq, y=ivq, mode="markers", name="Heston 'quotes'",
                    marker=dict(color=ORANGE, size=8))
    fig.add_scatter(x=fine, y=sf.vols(fine), name=f"SABR fit (β = {beta:g})",
                    line=dict(color=BLUE, width=2.5))
    fig.update_layout(xaxis_title="Strike K", yaxis_title="Implied vol",
                      yaxis_tickformat=".1%", height=380)
    st.plotly_chart(fig, width="stretch")
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("α", f"{sf.alpha:.4f}")
    c2.metric("ρ", f"{sf.rho:.3f}")
    c3.metric("ν", f"{sf.nu:.3f}")
    c4.metric("RMSE (vol pts)", f"{sf.rmse_vol * 100:.3f}")
    st.caption(
        f"Three parameters fit a whole expiry generated by a different model to "
        f"{sf.rmse_vol * 100:.2f} vol pts. That's the appeal of SABR as a smile "
        "parametrisation: smooth, few parameters, and the fitted (α, ρ, ν) can be tracked "
        "through time as a compact summary of the smile. The fit isn't exact because Heston's "
        "wings have a different shape; try other values of β to see how much they matter."
    )

# ---------------- Tab 2: Breeden-Litzenberger ----------------
with tab_bl:
    st.markdown(
        "The pipeline that turns quotes into a density: **(1)** out-of-the-money quotes → "
        "**(2)** implied vols → **(3)** a smooth curve through them → **(4)** call prices on a "
        "fine strike grid → **(5)** second differences. The quotes come from Heston, so the "
        "true density is known (from `cos_density`) and the result can be checked."
    )
    c1, c2, c3 = st.columns(3)
    T_b = c1.select_slider("Expiry T", [0.1, 0.25, 0.5, 1.0], value=0.5, key="Tb")
    n_q = c2.select_slider("Quotes", [15, 25, 40, 60], value=40)
    noise = c3.slider("Quote noise (vol pts)", 0.0, 0.5, 0.1, step=0.02) / 100
    c1, c2, c3 = st.columns(3)
    method = c1.radio("Smooth with", ["spline", "sabr"], horizontal=True)
    smooth_mult = c2.select_slider("Spline smoothing (× n·noise²)",
                                   [0.0, 0.25, 0.5, 1.0, 2.0, 4.0], value=1.0,
                                   disabled=(method != "spline"))
    seed_b = c3.number_input("Noise seed", value=1, step=1, key="seedb")

    H = HestonModel(r=0.0, kappa=1.5, vbar=0.04, gamma=0.5, rho=-0.7, v0=0.03)
    Fb = 100.0
    Kb = Fb * np.exp(np.linspace(-3.0, 2.0, n_q) * 0.2 * np.sqrt(T_b))
    iv_clean = black_implied_vol(otm_prices(H, Fb, Kb, T_b), Fb, Kb, T_b, Kb >= Fb)
    ok = np.isfinite(iv_clean)
    Kb, iv_clean = Kb[ok], iv_clean[ok]
    iv_noisy = iv_clean + noise * np.random.default_rng(int(seed_b)).standard_normal(len(Kb))

    s = 0.2 * np.sqrt(T_b)
    grid = np.linspace(Fb * np.exp(-5 * s), Fb * np.exp(4 * s), 2401)
    smoothing = smooth_mult * len(Kb) * noise**2
    d = implied_density(Fb, Kb, iv_noisy, T_b, method=method, K_grid=grid, smoothing=smoothing)
    true_dens = np.array(cos_density(H, T_b, list(np.log(grid / Fb)), 256, 12.0)) / grid

    fig = make_subplots(rows=1, cols=2, horizontal_spacing=0.08,
                        subplot_titles=("Steps 2–3: implied vols and the smooth curve",
                                        "Step 5: the implied density"))
    fig.add_scatter(x=Kb, y=iv_noisy, mode="markers", name="quotes (with noise)",
                    marker=dict(color=ORANGE, size=7), row=1, col=1)
    fig.add_scatter(x=grid, y=d.vols, name=f"smoothed ({method})",
                    line=dict(color=BLUE, width=2.5), row=1, col=1)
    fig.add_scatter(x=grid, y=true_dens, name="true Heston density",
                    line=dict(color=NEUTRAL, width=5), opacity=0.5, row=1, col=2)
    fig.add_scatter(x=grid, y=d.density, name="Breeden-Litzenberger",
                    line=dict(color=BLUE, width=2), row=1, col=2)
    for x in (Kb[0], Kb[-1]):
        fig.add_vline(x=x, line=dict(color=NEUTRAL, width=1, dash="dot"), row=1, col=2)
    fig.update_yaxes(tickformat=".0%", row=1, col=1)
    fig.update_xaxes(title_text="Strike K")
    fig.update_layout(height=440, legend=dict(orientation="h", y=-0.2))
    st.plotly_chart(fig, width="stretch")

    l1 = float(np.trapezoid(np.abs(d.density - true_dens), grid))
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Total probability", f"{d.mass:.4f}", help="Should be 1")
    c2.metric("Mean of S(T)", f"{d.mean:.3f}", help=f"Should be the forward, {Fb:g}")
    c3.metric("Most negative 'probability'", f"{min(d.density[1:-1].min(), 0.0):.2e}",
              help="Densities can't be negative: values below 0 are noise blown up")
    c4.metric("Error vs true density (L¹)", f"{l1:.4f}")
    st.caption(
        "Differentiating twice multiplies noise by 1/h². Set the smoothing to 0 with a little "
        "noise and the density turns into wild oscillations with negative 'probabilities'. "
        "Smoothing near n × noise² (the spline's error budget) gives back the true density. "
        "Dotted lines mark the quoted strike range: beyond it the smile is extrapolated, and "
        "the tails are an assumption, not data. The smile is extended with its end slope, "
        "because holding it flat would put a kink in the vols and a spike in the density."
    )
