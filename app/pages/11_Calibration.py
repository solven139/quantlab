import time

import numpy as np
import plotly.graph_objects as go
import streamlit as st

from quantlab import (BatesModel, HestonModel, MertonModel, black_implied_vol, calibrate,
                      otm_prices, profile)

BLUE = "#3987e5"
ORANGE = "#d95926"
GREEN = "#1baf7a"
VIOLET = "#4a3aa7"
NEUTRAL = "#8a8985"
SLICE_COLOURS = ["#b7d3f6", "#6da7ec", "#2a78d6", "#104281", "#061f45"]

st.title("Calibration")
st.markdown(
    "Every other page goes from **parameters to prices**. Calibration goes the other way: "
    "given the smile the market quotes, find the parameters that reproduce it. It's what a "
    "desk does every morning before any model can be used."
)
st.latex(r"\min_{\theta}\ \sum_{i}\left(\frac{V_{\text{model}}(K_i;\theta) - "
         r"V_{\text{market}}(K_i)}{\text{vega}_i}\right)^2 \;\approx\; "
         r"\sum_i\big(\sigma_{\text{model}}(K_i) - \sigma_{\text{market}}(K_i)\big)^2")
st.caption(
    "Dividing price errors by vega turns them into implied-vol errors, so a cheap far "
    "out-of-the-money option counts as much as an expensive at-the-money one. Prices come "
    "from the multi-strike COS pricer (the characteristic function is evaluated once for all "
    "strikes) and scipy's least_squares does the search. Here the 'market' is synthetic: "
    "quotes generated from a model you choose, plus noise, so we know the true answer."
)

# ---------------- model specifications ----------------
SPECS = {
    "Merton": dict(
        names=("σ", "ξ (jumps/yr)", "μ_J", "σ_J"),
        true=(0.15, 0.3, -0.15, 0.10),
        x0=(0.20, 1.0, -0.05, 0.05),
        bounds=([0.01, 0.0, -0.8, 0.01], [1.0, 5.0, 0.3, 0.8]),
        factory=lambda p: MertonModel(r=0.0, sigma=p[0], xi=p[1], mu_j=p[2], sigma_j=p[3]),
    ),
    "Heston": dict(
        names=("κ", "v̄", "γ", "ρ", "v₀"),
        true=(1.5, 0.04, 0.5, -0.7, 0.03),
        x0=(1.0, 0.06, 0.3, -0.3, 0.05),
        bounds=([0.05, 0.001, 0.01, -0.99, 0.001], [10.0, 0.5, 2.0, 0.99, 0.5]),
        factory=lambda p: HestonModel(r=0.0, kappa=p[0], vbar=p[1], gamma=p[2], rho=p[3],
                                      v0=p[4]),
    ),
    "Bates": dict(
        names=("κ", "v̄", "γ", "ρ", "v₀", "ξ", "μ_J", "σ_J"),
        true=(1.5, 0.03, 0.4, -0.6, 0.025, 0.3, -0.12, 0.08),
        x0=(1.0, 0.05, 0.3, -0.3, 0.04, 0.5, -0.05, 0.05),
        bounds=([0.05, 0.001, 0.01, -0.99, 0.001, 0.0, -0.8, 0.01],
                [10.0, 0.5, 2.0, 0.99, 0.5, 5.0, 0.3, 0.8]),
        factory=lambda p: BatesModel(r=0.0, kappa=p[0], vbar=p[1], gamma=p[2], rho=p[3],
                                     v0=p[4], xi=p[5], mu_j=p[6], sigma_j=p[7]),
    ),
}
EXPIRIES = {1: [0.25], 3: [0.1, 0.5, 1.0], 5: [0.1, 0.25, 0.5, 1.0, 2.0]}
F = 100.0

with st.sidebar:
    st.header("The 'market'")
    true_name = st.selectbox("Quotes generated by", list(SPECS), index=0)
    n_exp = st.radio("Expiries quoted", [1, 3, 5], index=0, horizontal=True,
                     format_func=lambda n: f"{n}")
    n_k = st.select_slider("Strikes per expiry", [10, 15, 25, 40], value=25)
    noise_bp = st.slider("Quote noise (vol pts)", 0.0, 1.0, 0.2, step=0.05,
                         help="Random error added to every implied vol, like a bid-ask spread")
    seed = st.number_input("Noise seed", value=0, step=1)
    st.header("The fit")
    fit_name = st.selectbox("Fit with model", list(SPECS), index=list(SPECS).index(true_name))
    st.caption("Fitting a different model from the one that made the quotes shows "
               "misspecification: the smile can't be matched however hard you search.")

true_spec, fit_spec = SPECS[true_name], SPECS[fit_name]
Ts = EXPIRIES[n_exp]


@st.cache_data(show_spinner=False)
def make_quotes(true_name, Ts, n_k, noise, seed):
    spec = SPECS[true_name]
    model = spec["factory"](np.array(spec["true"]))
    rng = np.random.default_rng(seed)
    Kss, ivss = [], []
    for T in Ts:
        Ks = F * np.exp(np.linspace(-2.5, 1.5, n_k) * 0.2 * np.sqrt(T))
        ivs = black_implied_vol(otm_prices(model, F, Ks, T), F, Ks, T, Ks >= F)
        ivs = ivs + noise * rng.standard_normal(n_k)
        ok = np.isfinite(ivs)
        Kss.append(Ks[ok])
        ivss.append(ivs[ok])
    return Kss, ivss


@st.cache_data(show_spinner="Calibrating (COS + least squares)...")
def run_fit(fit_name, Ts, Kss, ivss):
    spec = SPECS[fit_name]
    t0 = time.perf_counter()
    r = calibrate(spec["factory"], spec["x0"], spec["bounds"], [F] * len(Ts), Kss, Ts, ivss,
                  names=spec["names"])
    return dict(params=r.params, std=r.std_errors, corr=r.correlation, rmse=r.rmse_vol,
                cond=r.condition_number, nfev=r.nfev, model_ivs=r.model_ivs,
                iv_errors=r.iv_errors, seconds=time.perf_counter() - t0)


Kss, ivss = make_quotes(true_name, tuple(Ts), n_k, noise_bp / 100, int(seed))
fit = run_fit(fit_name, tuple(Ts), Kss, ivss)
fit_factory = fit_spec["factory"]

tab_fit, tab_err, tab_id = st.tabs(["Fit", "Errors per strike", "Identifiability"])

# ---------------- Tab 1: the fit ----------------
with tab_fit:
    fitted_model = fit_factory(fit["params"])
    fig = go.Figure()
    for j, (T, Ks, ivs) in enumerate(zip(Ts, Kss, ivss)):
        colour = SLICE_COLOURS[j + (5 - len(Ts))] if len(Ts) > 1 else BLUE
        fine = np.linspace(Ks[0], Ks[-1], 120)
        fiv = black_implied_vol(otm_prices(fitted_model, F, fine, T), F, fine, T, fine >= F)
        fig.add_scatter(x=fine / F, y=fiv, mode="lines", name=f"{fit_name} fit, T = {T:g}",
                        line=dict(color=colour, width=2.5))
        fig.add_scatter(x=Ks / F, y=ivs, mode="markers", name=f"quotes, T = {T:g}",
                        marker=dict(color=colour, size=7, line=dict(color="white", width=1)),
                        showlegend=False)
    fig.update_layout(xaxis_title="Moneyness K / F", yaxis_title="Implied volatility",
                      yaxis_tickformat=".1%", height=460)
    st.plotly_chart(fig, width="stretch")

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("RMSE (vol pts)", f"{fit['rmse'] * 100:.3f}",
              help="Root-mean-square implied-vol error of the fit")
    c2.metric("Noise (vol pts)", f"{noise_bp:.2f}")
    c3.metric("Function evaluations", f"{fit['nfev']}")
    c4.metric("Time", f"{fit['seconds'] * 1e3:.0f} ms")

    rows = []
    for i, n in enumerate(fit_spec["names"]):
        true_val = true_spec["true"][i] if fit_name == true_name else None
        rows.append({
            "parameter": n,
            "true": "" if true_val is None else f"{true_val:.4f}",
            "fitted": f"{fit['params'][i]:.4f}",
            "± std error": f"{fit['std'][i]:.2g}",
        })
    st.table(rows)
    if fit_name == true_name:
        st.caption(
            "With zero noise every parameter comes back to many digits. Add noise and some "
            "parameters stay pinned down while others drift far from the truth with large "
            "error bars, even though the fitted smile still looks perfect. The Identifiability "
            "tab shows why."
        )
    else:
        st.caption(
            f"The quotes came from {true_name}, the fit uses {fit_name}. If the RMSE stays well "
            "above the noise level, the fitted model can't produce the market's smile shape: "
            "for example Heston struggles with the steep short-dated skew that jumps create."
        )

# ---------------- Tab 2: errors ----------------
with tab_err:
    fig = go.Figure()
    for j, (T, Ks, err) in enumerate(zip(Ts, Kss, fit["iv_errors"])):
        colour = SLICE_COLOURS[j + (5 - len(Ts))] if len(Ts) > 1 else BLUE
        fig.add_bar(x=Ks / F, y=err * 100, name=f"T = {T:g}", marker_color=colour,
                    width=0.6 * np.min(np.diff(Ks / F)) if len(Ks) > 1 else 0.01)
    if noise_bp > 0:
        for y in (noise_bp, -noise_bp):
            fig.add_hline(y=y, line=dict(color=NEUTRAL, width=1, dash="dot"))
    fig.update_layout(xaxis_title="Moneyness K / F", yaxis_title="Model − quote (vol pts)",
                      barmode="overlay", height=420)
    st.plotly_chart(fig, width="stretch")
    st.caption(
        "Dotted lines: ± one standard deviation of the noise. A good fit leaves errors that look "
        "like that noise, scattered with no pattern. Systematic shapes, such as all positive in "
        "the wings and negative at the money, mean the model is the wrong shape for the data."
    )

# ---------------- Tab 3: identifiability ----------------
with tab_id:
    names = fit_spec["names"]
    corr = np.nan_to_num(fit["corr"])
    fig = go.Figure(go.Heatmap(z=corr, x=list(names), y=list(names), zmin=-1, zmax=1,
                               colorscale=[[0, ORANGE], [0.5, "#f5f5f4"], [1, BLUE]],
                               text=np.round(corr, 2), texttemplate="%{text}",
                               hovertemplate="%{y} vs %{x}: %{z:.3f}<extra></extra>"))
    fig.update_layout(height=380, yaxis_autorange="reversed",
                      title=dict(text="Correlation of the parameter estimates", x=0))
    st.plotly_chart(fig, width="stretch")
    st.caption(
        f"From the Jacobian at the optimum: cov ≈ s²(JᵀJ)⁻¹. Condition number of JᵀJ: "
        f"{fit['cond']:.2g}. Correlations near ±1 mean the data constrain only a combination "
        "of the two parameters, so one can be traded for the other with almost no change in fit."
    )

    st.subheader("Profile: fix one parameter, refit the rest")
    idx = st.selectbox("Parameter to profile", range(len(names)), format_func=lambda i: names[i],
                       index=1 if fit_name == "Merton" else 0)
    lo, hi = fit_spec["bounds"][0][idx], fit_spec["bounds"][1][idx]
    centre = fit["params"][idx]
    if lo >= 0 and centre > 0:
        grid = np.clip(centre * np.geomspace(0.3, 3.0, 9), max(lo, 1e-3), hi)
    else:
        grid = np.clip(centre + np.linspace(-0.4, 0.4, 9), lo + 1e-3, hi - 1e-3)

    @st.cache_data(show_spinner="Refitting along the profile...")
    def run_profile(fit_name, idx, grid, Ts, Kss, ivss, start):
        spec = SPECS[fit_name]
        return profile(spec["factory"], start, spec["bounds"], idx, list(grid),
                       [F] * len(Ts), Kss, list(Ts), ivss)

    prof = run_profile(fit_name, idx, tuple(np.round(grid, 6)), tuple(Ts), Kss, ivss,
                       tuple(fit["params"]))
    vals = np.array([p[0] for p in prof])
    rmses = np.array([p[1] for p in prof]) * 100
    fig = go.Figure()
    fig.add_scatter(x=vals, y=rmses, mode="lines+markers", name="best RMSE with this value fixed",
                    line=dict(color=BLUE, width=2.5), marker=dict(size=8))
    if noise_bp > 0:
        fig.add_hline(y=noise_bp, line=dict(color=NEUTRAL, width=1, dash="dot"),
                      annotation_text="noise level", annotation_position="top left")
    if fit_name == true_name:
        fig.add_vline(x=true_spec["true"][idx], line=dict(color=GREEN, width=1.5, dash="dash"),
                      annotation_text="true value")
    fig.update_layout(xaxis_title=f"{names[idx]} (fixed)", yaxis_title="RMSE (vol pts)",
                      height=400, yaxis_rangemode="tozero")
    st.plotly_chart(fig, width="stretch")
    st.caption(
        "A sharp V means the data pin this parameter down. A flat bottom means a whole range of "
        "values fits equally well: the others compensate. Try Merton, one expiry, 0.2 vol pts of "
        "noise, and profile ξ: frequent small crashes and rare large ones give the same "
        "smile, so the fit can't tell them apart. Fixing the crash size μ_J (or adding expiries, "
        "since jump effects fade with maturity at a different rate from diffusion) restores "
        "identification."
    )
